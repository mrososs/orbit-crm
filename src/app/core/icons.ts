/** `ChartColumn` → `chart-column`, `Columns3` → `columns-3` (matches Lucide's published names). */
function toIconData(icons: Record<string, unknown>): LucideIconData[] {
  return Object.entries(icons).map(([pascal, node]) => ({
    name: pascal
      .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
      .replace(/([a-zA-Z])(\d)/g, '$1-$2')
      .toLowerCase(),
    node: node as LucideIconData['node'],
  }));
}
